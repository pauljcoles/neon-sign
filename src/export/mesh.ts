// Extrudes 2D polygons into closed triangle meshes and writes binary STL.
import earcut from 'earcut';
import { type Poly, type Ring, area, difference, intersect, polyPaths, toPolys } from '../geom/clip';
import { bedRegion, type Params } from '../geom/design';
import type { Piece } from '../geom/split';

/** Flat list of triangles, 9 numbers (3 xyz vertices) per triangle. */
export type Tris = number[];

function dedupe(r: Ring): Ring {
  const out: Ring = [];
  for (const p of r) {
    const q = out[out.length - 1];
    if (!q || Math.abs(q[0] - p[0]) > 1e-6 || Math.abs(q[1] - p[1]) > 1e-6) out.push(p);
  }
  while (out.length > 2 && Math.abs(out[0][0] - out[out.length - 1][0]) < 1e-6 && Math.abs(out[0][1] - out[out.length - 1][1]) < 1e-6) out.pop();
  return out;
}

/** A closed prism between z0 and z1 for one polygon with holes. Outer rings CCW, holes CW, faces point outwards. */
export function prism(poly: Poly, z0: number, z1: number, tris: Tris = []): Tris {
  const outer = dedupe(poly.outer);
  if (outer.length < 3) return tris;
  if (area(outer) < 0) outer.reverse();
  const holes = poly.holes.map(dedupe).filter((h) => h.length >= 3).map((h) => (area(h) > 0 ? h.slice().reverse() : h));
  const rings = [outer, ...holes];
  const flat: number[] = [];
  const holeIdx: number[] = [];
  for (const r of rings) {
    if (r !== outer) holeIdx.push(flat.length / 2);
    for (const [x, y] of r) flat.push(x, y);
  }
  const idx = earcut(flat, holeIdx, 2);
  for (let t = 0; t < idx.length; t += 3) {
    let a = idx[t], b = idx[t + 1], c = idx[t + 2];
    const ccw = (flat[2 * b] - flat[2 * a]) * (flat[2 * c + 1] - flat[2 * a + 1]) - (flat[2 * b + 1] - flat[2 * a + 1]) * (flat[2 * c] - flat[2 * a]) > 0;
    if (!ccw) [b, c] = [c, b];
    // Top faces up (CCW seen from above), bottom faces down.
    tris.push(flat[2 * a], flat[2 * a + 1], z1, flat[2 * b], flat[2 * b + 1], z1, flat[2 * c], flat[2 * c + 1], z1);
    tris.push(flat[2 * a], flat[2 * a + 1], z0, flat[2 * c], flat[2 * c + 1], z0, flat[2 * b], flat[2 * b + 1], z0);
  }
  for (const r of rings) {
    for (let i = 0; i < r.length; i++) {
      const [ax, ay] = r[i], [bx, by] = r[(i + 1) % r.length];
      tris.push(ax, ay, z0, bx, by, z0, bx, by, z1);
      tris.push(ax, ay, z0, bx, by, z1, ax, ay, z1);
    }
  }
  return tris;
}

/**
 * A piece is two closed shells: the base plate and the walls (which start at z = 0 and overlap the plate).
 * Slicers merge overlapping shells, and keeping each shell a simple prism guarantees they are watertight.
 * The piece is centred on the middle of the bed (bed origin at a corner, as Bambu Studio uses).
 */
export function pieceMesh(piece: Piece, params: Params): Tris {
  return pieceShells(piece, params).flat();
}

/** The same mesh as `pieceMesh`, one closed triangle list per shell (base plate, engraved parts, each wall, bridges). */
export function pieceShells(piece: Piece, params: Params): Tris[] {
  // Centred on the part of the bed the printer can use, so it also clears a no-print corner.
  const r = bedRegion(params);
  const cx = (piece.bbox.minX + piece.bbox.maxX) / 2 - (r.x0 + r.x1) / 2, cy = (piece.bbox.minY + piece.bbox.maxY) / 2 - (r.y0 + r.y1) / 2;
  const move = (p: Poly): Poly => ({
    outer: p.outer.map(([x, y]) => [x - cx, y - cy]),
    holes: p.holes.map((h) => h.map(([x, y]) => [x - cx, y - cy])),
  });
  const shells: Tris[] = [];
  const add = (p: Poly, z0: number, z1: number) => { shells.push(prism(move(p), z0, z1)); };
  const depth = Math.min(params.engraveDepth, params.baseThickness - 0.6);
  if (piece.label?.length && depth > 0) {
    // The plate around the engraving runs full height; under the engraving it starts `depth` up.
    const base = polyPaths(piece.base);
    for (const p of toPolys(difference(base, piece.label))) add(p, 0, params.baseThickness);
    for (const p of toPolys(intersect(base, piece.label))) add(p, depth, params.baseThickness);
  } else {
    add(piece.base, 0, params.baseThickness);
  }
  for (const w of piece.walls) add(w, 0, params.baseThickness + params.wallHeight);
  for (const r of piece.raised ?? []) add(r, 0, params.bridgeHeight);
  return shells;
}

export function toBinaryStl(tris: Tris, name = 'neon-sign'): ArrayBuffer {
  const count = tris.length / 9;
  const buf = new ArrayBuffer(84 + count * 50);
  const view = new DataView(buf);
  const header = `${name} - generated by Glowline`.slice(0, 79);
  for (let i = 0; i < header.length; i++) view.setUint8(i, header.charCodeAt(i) & 0x7f);
  view.setUint32(80, count, true);
  let o = 84;
  for (let t = 0; t < tris.length; t += 9) {
    const ux = tris[t + 3] - tris[t], uy = tris[t + 4] - tris[t + 1], uz = tris[t + 5] - tris[t + 2];
    const vx = tris[t + 6] - tris[t], vy = tris[t + 7] - tris[t + 1], vz = tris[t + 8] - tris[t + 2];
    let nx = uy * vz - uz * vy, ny = uz * vx - ux * vz, nz = ux * vy - uy * vx;
    const len = Math.hypot(nx, ny, nz) || 1;
    nx /= len; ny /= len; nz /= len;
    view.setFloat32(o, nx, true); view.setFloat32(o + 4, ny, true); view.setFloat32(o + 8, nz, true);
    o += 12;
    for (let k = 0; k < 9; k++) { view.setFloat32(o, tris[t + k], true); o += 4; }
    view.setUint16(o, 0, true);
    o += 2;
  }
  return buf;
}
